#include <arch/series.h>

/**
@defgroup mpArchESP32ClassicBoot Boot

@ingroup mpArchESP32

The ROM copies this image into SRAM and jumps to _start. The APP CPU
stays in reset until mp_cpu_start releases it. The flash-boot watchdogs
are still armed until Reset_Handler clears them. There is no super
watchdog register in this series. VECBASE points at the window spill,
the level-2 slot and the level-1 exception slot. The level-2 slot runs
the TIMG tick and then FROM_CPU. Each core has its own level-2 save
area: PRID bit 13 selects it, because both cores take that vector.

@{
*/

extern unsigned long _sidata, _sdata, _edata, _sbss, _ebss;

#define _CL_ASM_WORD(value) _CL_ASM_WORD2(value)
#define _CL_ASM_WORD2(value) ".word " #value "\n"

int main(void);

/* TIMG flash-boot mode fires even when the watchdog enable bit is clear. */
static void _wdt_stop(unsigned long base) {
	cl_write(base + 0x64UL, CL_WDT_KEY);
	cl_clr(base + 0x48UL, (1UL << 31) | (1UL << 14));
	cl_write(base + 0x64UL, 0);
}

static void _watchdogs_off(void) {
	_wdt_stop(CL_TIMG0);
	_wdt_stop(CL_TIMG1);

	/* RTC WDT key is +0xA4 and config0 is +0x8C. Bit 10 is the flash-boot
	 * mode, not bit 12. */
	cl_write(CL_RTC + 0xA4UL, CL_WDT_KEY);
	cl_clr(CL_RTC + 0x8CUL, (1UL << 31) | (1UL << 10));
	cl_write(CL_RTC + 0xA4UL, 0);
}

static void _app_halt(void) {
	/* CTRL_A bit 0 holds the APP CPU in reset. CTRL_B bit 0 is its clock. */
	cl_write(CL_DPORT + 0x2CUL, 1);
	cl_write(CL_DPORT + 0x30UL, 0);
}

void Reset_Handler(void) {
	unsigned long *src;
	unsigned long *dst;

	_watchdogs_off();
	_app_halt();

	src = &_sidata;
	for(dst = &_sdata; dst < &_edata; dst++)
		*dst = *src++;

	for(dst = &_sbss; dst < &_ebss; dst++)
		*dst = 0;

	main();

	cl_write(CL_RTC, 1UL << 31);
	for(;;)
		;
}

