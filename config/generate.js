import fs from "fs"
import path from "path"
import { deviceRanks } from "./resolve.js"

const header = "Generated by miniPhi config. Do not edit."

function block(name, items) {
	if (!items.length)
		return [name + " :="]
	return [name + " := \\", ...items.map((item, index) => "\t" + item + (index < items.length - 1 ? " \\" : ""))]
}

function makefile(analysis, selection) {
	const { arch, series, mcu, toolchain } = analysis.target
	const flag = (template, value) => template.replace("{}", value)
	const cflags = [
		...toolchain.cflags,
		...analysis.defines.map((define) => flag(toolchain.defineFlag, define)),
		...analysis.includes.map((include) => flag(toolchain.includeFlag, include)),
	]
	const object = toolchain.object
	const target = [selection.board ? "board " + selection.board : "no board", arch.name, series.name, mcu.name, "toolchain " + toolchain.name].join(", ")
	const probeTargets = analysis.probes.flatMap((probe) => probe.targets.map((item) => ({ ...item, probe: probe.label })))
	const probeRules = probeTargets.flatMap((item) => [
		"# " + item.label + " (" + item.probe + ")",
		item.name + ": $(TARGET)",
		"\t$(ROOT)/" + item.script + (item.args ? " " + item.args : ""),
		"",
	])

	return [
		"# " + header,
		"# " + target,
		"",
		"ROOT := ..",
		"MCU := " + mcu.name,
		...(mcu.cpu ? ["CPU := " + mcu.cpu] : []),
		...analysis.vars.map((item) => item.name + " ?= " + item.value),
		...analysis.settings.filter((setting) => setting.emit === "make").map((setting) => setting.name + " := " + setting.value),
		"",
		"CC := " + toolchain.cc,
		"TARGET := " + toolchain.output,
		...(toolchain.linkerScript && mcu.ld ? ["LDSCRIPT := $(ROOT)/" + mcu.ld] : []),
		"",
		...block("CFLAGS", cflags),
		"",
		...block("LDFLAGS", toolchain.ldflags || []),
		"",
		"LIBS := " + (toolchain.libs || []).join(" "),
		"",
		...block("SRCS", analysis.sources.map((source) => "$(ROOT)/" + source)),
		"",
		"OBJS := $(patsubst $(ROOT)/%.c,obj/%" + object + ",$(SRCS))",
		"",
		".PHONY: " + ["all", "clean", ...probeTargets.map((item) => item.name)].join(" "),
		"",
		"all: $(TARGET)",
		"",
		"$(TARGET): $(OBJS)" + (toolchain.linkerScript ? " $(LDSCRIPT)" : ""),
		"\t" + toolchain.link,
		"",
		"obj/%" + object + ": $(ROOT)/%.c include/autoconf.h include/pinout.h $(wildcard include/gen/*.h)",
		"\t@mkdir -p $(@D)",
		"\t" + toolchain.compile,
		"",
		"-include $(OBJS:" + object + "=.d)",
		"",
		...probeRules,
		"clean:",
		"\trm -rf obj $(TARGET) miniphi.map",
		"",
	].join("\n")
}

function autoconf(analysis, selection) {
	const { arch, series, mcu, toolchain } = analysis.target
	const active = (list) => list.filter((item) => item.state !== "off").map((item) => item.name).join(" ")
	const build = {
		BOARD: JSON.stringify(selection.board || "none"),
		APP: JSON.stringify(analysis.app ? analysis.app.name : "none"),
		ARCH: JSON.stringify(arch.name),
		SERIES: JSON.stringify(series.name),
		MCU: JSON.stringify(mcu.label),
		TOOLCHAIN: JSON.stringify(toolchain.label),
		MODULES: JSON.stringify(active(analysis.modules)),
		DRIVERS: JSON.stringify(active(analysis.drivers)),
		FLASH: mcu.flash + "UL",
		RAM: mcu.ram + "UL",
	}

	const lines = ["/* " + header + " */", "#ifndef _HAVE_AUTOCONF_H", "#define _HAVE_AUTOCONF_H", ""]
	for (const [name, value] of Object.entries(build))
		lines.push("#define PHI_BUILD_" + name + " " + value)
	lines.push("")
	for (const define of analysis.headerDefines)
		lines.push("#define " + define)
	lines.push("")
	for (const setting of analysis.settings.filter((item) => item.emit === "header")) {
		if (setting.type === "bool") {
			if (setting.value)
				lines.push("#define " + setting.name)
		}
		else
			lines.push("#define " + setting.name + " " + setting.value)
	}
	lines.push("", "#endif", "")
	return lines.join("\n")
}

function pinout(analysis) {
	const lines = [
		"/* " + header + " */",
		"/* mp_options_t options[] = PHI_LED_RED; */",
		"#ifndef _HAVE_PINOUT_H",
		"#define _HAVE_PINOUT_H",
		"",
	]
	const ranked = new Map()
	for (const device of analysis.devices) {
		if (device.driver) {
			if (!ranked.has(device.driver))
				ranked.set(device.driver, [])
			ranked.get(device.driver).push(device.macro)
		}
		const pairs = []
		for (const option of device.schema) {
			const value = device.values[option.name]
			if (value === undefined || value === false)
				continue
			pairs.push("\t{ " + JSON.stringify(option.name) + ", " + JSON.stringify(String(value)) + " }, \\")
		}
		lines.push("/* " + device.label + " */")
		lines.push("#define " + device.macro + " { \\")
		lines.push(...pairs)
		lines.push("\t{ NULL, NULL } \\")
		lines.push("}")
		lines.push("")
	}
	if (ranked.size) {
		lines.push("/* devices of each driver by rank, for apps that do not know the board */")
		for (const [driver, macros] of ranked)
			macros.slice(0, deviceRanks.length).forEach((macro, rank) =>
				lines.push("#define PHI_" + driver + "_" + deviceRanks[rank].toUpperCase() + " " + macro))
		lines.push("")
	}
	lines.push("#endif", "")
	return lines.join("\n")
}

function key(name) {
	return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name)
}

export function toJs(value, indent = "") {
	const next = indent + "\t"
	if (Array.isArray(value)) {
		if (!value.length)
			return "[]"
		if (value.every((item) => typeof item !== "object" || item === null))
			return "[" + value.map((item) => JSON.stringify(item)).join(", ") + "]"
		return "[\n" + value.map((item) => next + toJs(item, next) + ",").join("\n") + "\n" + indent + "]"
	}
	if (value && typeof value === "object") {
		const entries = Object.entries(value).filter(([, item]) => item !== undefined)
		if (!entries.length)
			return "{}"
		if (entries.every(([, item]) => typeof item !== "object" || item === null) && entries.length <= 5) {
			const inline = "{ " + entries.map(([name, item]) => key(name) + ": " + JSON.stringify(item)).join(", ") + " }"
			if (inline.length <= 100)
				return inline
		}
		return "{\n" + entries.map(([name, item]) => next + key(name) + ": " + toJs(item, next) + ",").join("\n") + "\n" + indent + "}"
	}
	return JSON.stringify(value)
}

function cryptoHardware(analysis) {
	const items = analysis.crypto || []
	const cryptoMax = 16
	const lines = [
		"/* " + header + " */",
		"/* crypto in this firmware, and the blocks the chip declares; included after mp.h */",
		"#ifndef _HAVE_GEN_CRYPTO_H",
		"#define _HAVE_GEN_CRYPTO_H",
		"",
		"#define MP_CRYPTO_MAX " + cryptoMax,
		"#define MP_CRYPTO_COUNT " + items.length,
		"",
	]
	if (items.length > cryptoMax)
		lines.push("#error more than MP_CRYPTO_MAX crypto entries", "")
	lines.push(
		"typedef struct mp_crypto_s {",
		"\tconst char *name;",
		"\tconst char *label;",
		"\tconst char *family;",
		"\tconst char *familyLabel;",
		"\tmp_bool_t hardware;",
		"\tmp_bool_t built;",
		"} mp_crypto_t;",
		"",
	)
	lines.push("#endif", "")
	/* outside the guard, so a second include with MP_CRYPTO_TABLE set emits the table once */
	if (items.length) {
		lines.push("", "#ifdef MP_CRYPTO_TABLE", "static const mp_crypto_t mp_crypto[] = {")
		for (const item of items)
			lines.push("\t{ " + JSON.stringify(item.name) + ", " + JSON.stringify(item.label) + ", " + JSON.stringify(item.family) + ", " + JSON.stringify(item.familyLabel) + ", " + (item.hardware ? "YES" : "NO") + ", " + (item.built ? "YES" : "NO") + " },")
		lines.push("};", "#undef MP_CRYPTO_TABLE", "#endif")
	}
	lines.push("")
	return lines.join("\n")
}

export function buildFiles(analysis, selection) {
	return {
		"config.js": "// " + header + "\nexport const config = " + toJs(selection) + "\n",
		"Makefile": makefile(analysis, selection),
		"include/autoconf.h": autoconf(analysis, selection),
		"include/pinout.h": pinout(analysis),
		"include/gen/crypto.h": cryptoHardware(analysis),
	}
}

export function writeBuild(root, analysis, files) {
	const buildDir = path.join(root, "build")
	fs.rmSync(path.join(buildDir, "include"), { recursive: true, force: true })
	for (const [name, content] of Object.entries(files)) {
		const file = path.join(buildDir, name)
		fs.mkdirSync(path.dirname(file), { recursive: true })
		fs.writeFileSync(file, content)
	}
	for (const header of analysis.headers) {
		const link = path.join(buildDir, header.link)
		fs.mkdirSync(path.dirname(link), { recursive: true })
		fs.symlinkSync(path.relative(path.dirname(link), path.join(root, header.target)), link)
	}
	return [...Object.keys(files).map((name) => "build/" + name), "build/include/ (" + analysis.headers.length + " headers linked)"]
}

export function boardSource(dir, vendor, label, selection) {
	const name = path.posix.basename(dir)
	const board = {
		kind: "board",
		name,
		vendor,
		label: label || name,
		description: "",
		arch: selection.arch,
		series: selection.series,
		mcu: selection.mcu,
		toolchain: selection.toolchain,
		requires: selection.probes || [],
		app: selection.app || null,
		sources: (selection.sources || []).map((source) => path.posix.relative(dir, source)),
		defines: selection.defines || [],
		modules: selection.modules || [],
		drivers: selection.drivers || [],
		settings: selection.settings || {},
		devices: selection.devices || [],
	}
	return "export const phi = " + toJs(board) + "\n"
}
