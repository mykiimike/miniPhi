function mldsaSign(file, prefix) {
	const rows = []
	for (const g of groups(file)) {
		const seed = hex(g.privateSeed)
		if (seed.length !== 32)
			continue
		for (const t of g.tests) {
			if (t.ctx)
				continue
			if ((t.flags || []).includes("Randomized") || (t.flags || []).includes("Internal"))
				continue
			if (t.result !== "valid" || !t.sig)
				continue
			rows.push({
				id: t.tcId, result: 1, flags: t.flags,
				seed, msg: hex(t.msg), sig: hex(t.sig),
			})
		}
	}
	const picked = []
	const many = rows.find((row) => (row.flags || []).includes("ManySteps"))
	const bound = rows.find((row) => (row.flags || []).includes("BoundaryCondition") && !(row.flags || []).includes("ManySteps"))
	for (const row of rows) {
		if (picked.length >= 2)
			break
		picked.push(row)
	}
	for (const extra of [many, bound]) {
		if (extra && !picked.includes(extra))
			picked.push(extra)
	}
	return emit("common/crypto/sign/mldsa/test/" + prefix + "_sign.h",
		"Wycheproof testvectors_v1/" + file + " @ " + commit + ". Deterministic external signatures: two KATs, one ManySteps, one boundary. mu is recorded by Wycheproof and is not an API input.",
		prefix + "s", ["seed", "msg", "sig"], picked)
}
