function hmac(alg, key, data) {
	return crypto.createHmac(alg, key).update(data).digest()
}
function drbg(alg, entropy, nonce, personal, outLen) {
	const size = crypto.createHash(alg).digest().length
	let K = Buffer.alloc(size, 0)
	let V = Buffer.alloc(size, 1)
	const update = (provided) => {
		K = hmac(alg, K, Buffer.concat([V, Buffer.from([0]), provided]))
		V = hmac(alg, K, V)
		if (provided.length) {
			K = hmac(alg, K, Buffer.concat([V, Buffer.from([1]), provided]))
			V = hmac(alg, K, V)
		}
	}
	update(Buffer.concat([entropy, nonce, personal]))
	let temp = Buffer.alloc(0)
	while (temp.length < outLen) {
		V = hmac(alg, K, V)
		temp = Buffer.concat([temp, V])
	}
	update(Buffer.alloc(0))
	return temp.subarray(0, outLen)
}
