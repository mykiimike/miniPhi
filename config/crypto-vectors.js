function load(name) {
	return JSON.parse(fs.readFileSync(path.join(dir, name), "utf8"))
}

function hex(s) {
	if (s == null || s === "")
		return Buffer.alloc(0)
	return Buffer.from(s, "hex")
}

function fit(buf, n) {
	let b = buf
	while (b.length > n && b[0] === 0)
		b = b.subarray(1)
	if (b.length > n)
		return null
	if (b.length === n)
		return b
	const out = Buffer.alloc(n)
	b.copy(out, n - b.length)
	return out
}

const RES = { valid: 1, invalid: 2, acceptable: 3, refuse: 4 }

function keep(rows, limit) {
	if (rows.length <= limit)
		return rows
	const rest = []
	const plain = []
	for (const row of rows) {
		if (row.result !== 1 || (row.flags && row.flags.length))
			rest.push(row)
		else
			plain.push(row)
	}
	const step = Math.max(1, Math.floor(plain.length / 8))
	for (let i = 0; i < plain.length && rest.length < limit; i += step)
		rest.push(plain[i])
	return rest
}

function emit(rel, comment, prefix, fields, rows) {
	const blob = []
	const lines = []
	let valid = 0
	let invalid = 0
	let acceptable = 0
	let refuse = 0
	for (const row of rows) {
		if (row.result === 1)
			valid++
		else if (row.result === 2)
			invalid++
		else if (row.result === 3)
			acceptable++
		else
			refuse++
		const off = blob.length
		const ns = []
		for (const field of fields) {
			const part = row[field] || Buffer.alloc(0)
			if (part.length > 65535)
				throw new Error(prefix + " field " + field + " is " + part.length)
			ns.push(part.length)
			for (const b of part)
				blob.push(b)
		}
		lines.push("\t{ " + row.id + ", " + row.result + ", " + off + ", { " + ns.join(", ") + " } },")
	}
	const bytes = []
	for (let i = 0; i < blob.length; i += 12) {
		const slice = blob.slice(i, i + 12).map((b) => "0x" + b.toString(16).padStart(2, "0"))
		bytes.push("\t" + slice.join(", ") + ",")
	}
	if (!bytes.length)
		bytes.push("\t0")
	const nfield = fields.length
	const text = `/* ${comment}
 * ${prefix}: valid ${valid}, invalid ${invalid}, acceptable ${acceptable}, refuse ${refuse}. Fields: ${fields.join(", ")}.
 * Regenerated by config/crypto-vectors.js.
 */
#ifndef ${prefix.toUpperCase()}_H
#define ${prefix.toUpperCase()}_H
#include <stdint.h>
typedef struct { uint32_t id; uint8_t result; uint32_t off; uint16_t n[${nfield}]; } ${prefix}_vec_t;
static const uint8_t ${prefix}_blob[] = {
${bytes.join("\n")}
};
static const ${prefix}_vec_t ${prefix}_vec[] = {
${lines.join("\n")}
};
#define ${prefix.toUpperCase()}_COUNT ((unsigned)(sizeof(${prefix}_vec) / sizeof(${prefix}_vec[0])))
static const uint8_t *${prefix}_at(unsigned i, unsigned field) {
	const uint8_t *p = ${prefix}_blob + ${prefix}_vec[i].off;
	unsigned f;

	for(f = 0; f < field; f++)
		p += ${prefix}_vec[i].n[f];
	return(p);
}
#endif
`
	const file = path.join(root, rel)
	fs.mkdirSync(path.dirname(file), { recursive: true })
	fs.writeFileSync(file, text)
	return { valid, invalid, acceptable, refuse, n: rows.length, file: rel }
}

