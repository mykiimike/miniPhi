function rsaRows(file, bits) {
	const rows = []
	const mod = bits / 8
	for (const g of groups(file)) {
		if (g.sha !== "SHA-256" || g.keySize !== bits)
			continue
		const n = fit(hex(g.publicKey.modulus), mod)
		const e = fit(hex(g.publicKey.publicExponent), 4)
		if (!n || !e)
			continue
		const pk = Buffer.concat([n, e])
		for (const t of g.tests) {
			rows.push({
				id: t.tcId, result: RES[t.result], flags: t.flags,
				pk, msg: hex(t.msg), sig: hex(t.sig),
			})
		}
	}
	return rows
}

