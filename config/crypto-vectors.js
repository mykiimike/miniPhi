function blockMode(rel, prefix, mode, ivlen) {
	const rows = []
	const pt = Buffer.from("6bc1bee22e409f96e93d7e117393172aae2d8a571e03ac9c9eb76fac45af8e5130c81c46a35ce411e5fbc1191a0a52eff69f2445df4f9b17ad2b417be66c3710", "hex")
	let id = 1
	for (const bits of [128, 256]) {
		const k = Buffer.alloc(bits / 8)
		for (let b = 0; b < k.length; b++)
			k[b] = b + 1
		const iv = Buffer.alloc(ivlen)
		for (let b = 0; b < iv.length; b++)
			iv[b] = b
		const c = crypto.createCipheriv("aes-" + bits + "-" + mode, k, iv)
		c.setAutoPadding(false)
		const ct = Buffer.concat([c.update(pt), c.final()])
		rows.push({ id: id++, result: 1, key: k, iv, pt, ct })
	}
	summary.push(emit(rel, "NIST SP 800-38A style inputs (key 0102.., iv 0001.., four blocks). Ciphertext from OpenSSL AES-" + mode.toUpperCase() + ".",
		prefix, ["key", "iv", "pt", "ct"], rows))
}
