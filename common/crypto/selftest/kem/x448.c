mp_bool_t mp_crypto_selftest_x448(void) {
	uint8_t out[56], seed[56], coins[56];
	uint8_t priv[56], pub[56], ct[56], ss[64], back[64];
	unsigned int i;
	mp_bool_t ok = NO;

	mp_crypto_x448(out, _scalar, _point);
	if(mp_crypto_selftest_equal(out, _product, 56) != YES)
		goto done;
	for(i = 0; i < 56; i++)
		seed[i] = (uint8_t)i;
	if(mp_crypto_x448_keypair(seed, 56, priv, pub) != TRUE)
		goto done;
	if(mp_crypto_selftest_equal(pub, _pk, 56) != YES)
		goto done;
	for(i = 0; i < 56; i++)
		coins[i] = (uint8_t)(56 + i);
	if(mp_crypto_x448_encaps(pub, coins, 56, ss, ct) != 56)
		goto done;
	if(mp_crypto_selftest_equal(ct, _enc, 56) != YES)
		goto done;
	if(mp_crypto_selftest_equal(ss, _ss, 64) != YES)
		goto done;
	if(mp_crypto_x448_decaps(priv, ct, 56, back) != YES)
		goto done;
	if(mp_crypto_selftest_equal(back, ss, 64) != YES)
		goto done;
	ct[0] ^= 1;
	if(mp_crypto_x448_decaps(priv, ct, 56, back) != YES)
		goto done;
	if(mp_crypto_selftest_equal(back, ss, 64) == YES)
		goto done;
	memset(ct, 0, 56);
	if(mp_crypto_x448_decaps(priv, ct, 56, back) != NO)
		goto done;
	memset(pub, 0, 56);
	if(mp_crypto_x448_encaps(pub, coins, 56, ss, ct) != 0)
		goto done;
	ok = YES;
done:
	memset(out, 0, sizeof(out));
	memset(seed, 0, sizeof(seed));
	memset(coins, 0, sizeof(coins));
	memset(priv, 0, sizeof(priv));
	memset(pub, 0, sizeof(pub));
	memset(ct, 0, sizeof(ct));
	memset(ss, 0, sizeof(ss));
	memset(back, 0, sizeof(back));
	return(ok);
}

