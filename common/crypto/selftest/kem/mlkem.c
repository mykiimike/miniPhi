static mp_bool_t _sha(const void *data, unsigned int len, const uint8_t expect[32]) {
	uint8_t dig[32];
	mp_bool_t ok;

	mp_crypto_sha3_256(data, len, dig);
	ok = mp_crypto_selftest_equal(dig, expect, 32);
	memset(dig, 0, sizeof(dig));
	return(ok);
}

mp_bool_t mp_crypto_selftest_mlkem(void) {
	static uint8_t priv[MP_CRYPTO_MLKEM_PRIV];
	static uint8_t pub[MP_CRYPTO_MLKEM_PUB];
	static uint8_t ct[MP_CRYPTO_MLKEM_CT];
	uint8_t seed[64], coins[32], ss[32], back[32];
	unsigned int i;
	mp_bool_t ok = NO;

	for(i = 0; i < 64; i++)
		seed[i] = (uint8_t)i;
	for(i = 0; i < 32; i++)
		coins[i] = (uint8_t)i;
	if(mp_crypto_mlkem_keypair(seed, 64, priv, pub) != TRUE)
		goto done;
	if(_sha(priv, MP_CRYPTO_MLKEM_PRIV, _dk) != YES)
		goto done;
	if(_sha(pub, MP_CRYPTO_MLKEM_PUB, _ek) != YES)
		goto done;
	if(mp_crypto_mlkem_encaps(pub, coins, 32, ss, ct) != MP_CRYPTO_MLKEM_CT)
		goto done;
	if(_sha(ct, MP_CRYPTO_MLKEM_CT, _ct) != YES)
		goto done;
	if(mp_crypto_selftest_equal(ss, _ss, 32) != YES)
		goto done;
	if(mp_crypto_mlkem_decaps(priv, ct, MP_CRYPTO_MLKEM_CT, back) != YES)
		goto done;
	if(mp_crypto_selftest_equal(back, ss, 32) != YES)
		goto done;
	ct[0] ^= 1;
	if(mp_crypto_mlkem_decaps(priv, ct, MP_CRYPTO_MLKEM_CT, back) != YES)
		goto done;
	if(mp_crypto_selftest_equal(back, ss, 32) == YES)
		goto done;
	ok = YES;
done:
	memset(priv, 0, sizeof(priv));
	memset(pub, 0, sizeof(pub));
	memset(ct, 0, sizeof(ct));
	memset(seed, 0, sizeof(seed));
	memset(coins, 0, sizeof(coins));
	memset(ss, 0, sizeof(ss));
	memset(back, 0, sizeof(back));
	return(ok);
}

