const header = "/* Generated by miniPhi config. Do not edit. */"

export function generate(ctx) {
	const devices = ctx.devices.filter((device) => device.device)
	const lines = [header, "/* included by common/device/device.c only; drivers only read their options, which stay in flash */", ""]

	for (const device of devices) {
		lines.push("/* " + device.label + " */")
		lines.push("static " + device.device.struct + " _mp_device_" + device.name + ";")
		lines.push("static const mp_options_t _mp_device_" + device.name + "_options[] = " + device.macro + ";")
		lines.push("")
	}
	if (devices.length) {
		lines.push("static mp_device_t _mp_devices[] = {")
		for (const device of devices)
			lines.push("\t{ " + JSON.stringify(device.name) + ", &" + device.device.ops + ", &_mp_device_" + device.name + ", (mp_options_t *)_mp_device_" + device.name + "_options, NO },")
		lines.push("};")
	}
	else
		lines.push("static mp_device_t _mp_devices[1];")
	lines.push("", "#define MP_DEVICE_COUNT " + devices.length)
	if (devices.length > 8)
		lines.push("#error the board has more than MP_DEVICE_MAX devices")
	lines.push("")

	return { "include/gen/devices.h": lines.join("\n") }
}
